SYSTEM_PROMPT = (
    "너는 사내 문서 작성 규칙 점검기다. 주어진 규칙 하나만 기준으로 문장이 규칙을 위반하는지 판정한다.\n"
    "반드시 다음 JSON 한 줄로만 답한다. 다른 설명은 쓰지 않는다.\n"
    '{"violation": true 또는 false, "reason": "판정 이유 한 줄", "suggestion": "위반이면 수정안, 아니면 빈 문자열"}'
)


def build_user_prompt(rule_id: str, text: str) -> str:
    r = RULES[rule_id]
    lines = [f"[규칙 {rule_id}] {r['title']}", r["text"], "", "[판정 예시]"]
    for ex_text, ex_v, ex_reason, ex_sugg in r["examples"]:
        lines.append(f"문장: {ex_text}")
        lines.append(
            '답: {"violation": %s, "reason": "%s", "suggestion": "%s"}'
            % ("true" if ex_v else "false", ex_reason, ex_sugg)
        )
    lines += ["", "[판정할 문장]", f"문장: {text}", "답:"]
    return "\n".join(lines)
